CREATE TABLE IF NOT EXISTS documents (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, object_key TEXT NOT NULL UNIQUE,
 url TEXT NOT NULL DEFAULT '', size INTEGER NOT NULL, sha256 TEXT NOT NULL,
 sku TEXT NOT NULL DEFAULT '', marketplace TEXT NOT NULL DEFAULT '',
 language TEXT NOT NULL DEFAULT '', document_type TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL DEFAULT 'publishing', created_at TEXT NOT NULL, checked_at TEXT
);
CREATE TABLE IF NOT EXISTS usage (id INTEGER PRIMARY KEY CHECK(id=1), bytes INTEGER NOT NULL DEFAULT 0, paused INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO usage(id) VALUES(1);
CREATE TABLE IF NOT EXISTS login_attempts (id TEXT PRIMARY KEY, count INTEGER NOT NULL DEFAULT 0);
